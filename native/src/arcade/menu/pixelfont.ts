export type PixelText = {
  /** Células acesas (coluna, linha) na grade do texto inteiro. */
  cells: [number, number][];
  cols: number;
  rows: number;
};

/** Texto → células. Caractere que a fonte não tem vira espaço (nunca estoura). */
export function pixelText(text: string): PixelText {
  const cells: [number, number][] = [];
  let x = 0;
  for (const raw of text.toUpperCase()) {
    const g = G[raw] ?? G[' '];
    for (let r = 0; r < GLYPH_H; r++) for (let c = 0; c < GLYPH_W; c++) if (g[r][c] === '#') cells.push([x + c, r]);
    x += GLYPH_W + GAP;
  }
  return {cells, cols: Math.max(0, x - GAP), rows: GLYPH_H};
}

export const hasGlyph = (ch: string) => ch.toUpperCase() in G;
